/**
 * Expo config plugin: set Android packagingOptions pickFirsts for duplicate
 * META-INF license files.
 *
 * Why this exists: `react-native-mail-engine` pulls in `com.sun.mail:android-mail`
 * and `com.sun.mail:android-activation`, which both ship `META-INF/LICENSE.md`
 * (and LICENSE/NOTICE). Without a `pickFirsts`, the release build fails at
 * `:app:mergeReleaseJavaResource` with:
 *
 *   > 2 files found with path 'META-INF/LICENSE.md' from inputs:
 *       - com.sun.mail:android-mail:1.6.7/android-mail-1.6.7.jar
 *       - com.sun.mail:android-activation:1.6.7/android-activation-1.6.7.jar
 *
 * `android/` is regenerated by `expo prebuild --clean`, so this cannot live in
 * a checked-in Gradle file — it must be injected at prebuild time. That is what
 * this plugin does (AGENTS.md: never hand-edit `android/`).
 */
const { withAppBuildGradle } = require('@expo/config-plugins');

const PICK_FIRSTS = [
  'META-INF/LICENSE.md',
  'META-INF/LICENSE',
  'META-INF/NOTICE.md',
  'META-INF/NOTICE',
];

/**
 * Add `pickFirsts` entries to the `packagingOptions { ... }` block.
 *
 * Anchored on `packagingOptions {` and closed by brace counting rather than a
 * fixed offset, so it survives prebuild changing its indentation or adding
 * entries.
 */
function addPackagingPickFirsts(contents) {
  const anchor = contents.indexOf('packagingOptions {');
  if (anchor === -1) {
    throw new Error(
      'withAndroidPackagingPickFirsts: no packagingOptions block in app/build.gradle. ' +
        'Expo prebuild output changed; update this plugin.',
    );
  }

  // Find the matching close brace of the packagingOptions block via simple
  // brace counting (ignoring braces inside single-quoted strings, which the
  // generated file never has in this block).
  let depth = 0;
  let close = -1;
  for (let i = anchor; i < contents.length; i++) {
    const ch = contents[i];
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) {
        close = i;
        break;
      }
    }
  }
  if (close === -1) {
    throw new Error(
      'withAndroidPackagingPickFirsts: could not find closing brace of packagingOptions block.',
    );
  }

  const entries = PICK_FIRSTS.map(
    (p) => `        pickFirsts += '${p.replace(/'/g, "\\'")}'`,
  ).join('\n');

  return (
    contents.slice(0, close) +
    '\n' +
    entries +
    '\n' +
    contents.slice(close)
  );
}

module.exports = function withAndroidPackagingPickFirsts(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error(
        'withAndroidPackagingPickFirsts: expected a Groovy app/build.gradle, got ' +
          cfg.modResults.language,
      );
    }
    if (!cfg.modResults.contents.includes("pickFirsts += 'META-INF/LICENSE.md'")) {
      cfg.modResults.contents = addPackagingPickFirsts(cfg.modResults.contents);
    }
    return cfg;
  });
};
